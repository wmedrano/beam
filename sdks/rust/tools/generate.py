"""Regenerate private Rust bindings from Beam's authoritative model.

Generation requires Python protobuf (tools/requirements.txt), protoc 34.0,
and protoc-gen-rust-grpc 0.9.0. Ordinary Cargo builds require none of them.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

from google.protobuf import descriptor_pb2, descriptor_pool, message_factory

SDK = Path(__file__).resolve().parents[1]
REPO = SDK.parents[1]
MODEL = SDK / "crates/beam-model/src"
HEADER = "\n".join(
    "//" + line[1:] if line.startswith("#") else "//"
    for line in Path(__file__).read_text().splitlines()[1:15]
) + "\n\n"
INCLUDES = [
    REPO / "model" / name / "src/main/proto"
    for name in ("pipeline", "job-management", "fn-execution")
]
INCLUDES.append(SDK / "proto")


def run(args):
    subprocess.run([str(arg) for arg in args], check=True)


def constants(descriptor):
    """Read custom enum options via descriptors, including nested enums."""
    files = descriptor_pb2.FileDescriptorSet.FromString(descriptor)
    pool = descriptor_pool.DescriptorPool()
    for file in files.file:
        pool.AddSerializedFile(file.SerializeToString())
    option_type = message_factory.GetMessageClass(
        pool.FindMessageTypeByName("google.protobuf.EnumValueOptions")
    )
    extensions = {
        name: pool.FindExtensionByName("org.apache.beam.model.pipeline.v1." + name)
        for name in ("beam_urn", "beam_constant")
    }
    result = {}

    def enums(container, prefix):
        for enum in container.enum_type:
            for value in enum.value:
                opts = option_type.FromString(value.options.SerializeToString())
                for kind, extension in extensions.items():
                    if opts.HasExtension(extension):
                        path = prefix + [enum.name, value.name]
                        name = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", "_".join(path)).upper()
                        if name in result:
                            raise ValueError("duplicate constant " + name)
                        result[name] = (kind, opts.Extensions[extension])

    def message(msg, prefix):
        prefix = prefix + [msg.name]
        enums(msg, prefix)
        for nested in msg.nested_type:
            message(nested, prefix)

    for file in files.file:
        if file.package.startswith("org.apache.beam."):
            enums(file, [])
            for msg in file.message_type:
                message(msg, [])
    lines = [HEADER, "// @generated by tools/generate.py from model enum options.\n"]
    for name, (_, value) in sorted(result.items()):
        lines.append(f"pub const {name}: &str = {json.dumps(value)};\n")
    lines.append("pub const ALL: &[(&str, &str)] = &[\n")
    for name, (kind, _) in sorted(result.items()):
        if kind == "beam_urn":
            lines.append(f'    ("{name}", {name}),\n')
    lines.append("] ;\n")
    return "".join(lines).encode()


def snake(name):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).lower()


def tonic_clients(descriptor):
    """Generate client-only Tonic calls using our official-message codec.

    Names, paths, stream directions and message types come from descriptors.
    No hand-maintained second protobuf model or protoc plugin is involved.
    """
    files = descriptor_pb2.FileDescriptorSet.FromString(descriptor)
    types = {}

    def messages(msg, package, parents):
        types["." + package + "." + ".".join(parents + [msg.name])] = "crate::" + "::".join([snake(p) for p in parents] + [msg.name])
        for nested in msg.nested_type:
            messages(nested, package, parents + [msg.name])

    for file in files.file:
        for message in file.message_type:
            messages(message, file.package, [])
    lines = [HEADER, "// @generated by tools/generate.py from service descriptors.\n"]
    for file in files.file:
        if not file.package.startswith("org.apache.beam."):
            continue
        for service in file.service:
            lines.append(f"pub mod {snake(service.name)}_client {{\n")
            lines.append(f"    #[derive(Debug, Clone)]\n    pub struct {service.name}Client {{ inner: tonic::client::Grpc<tonic::transport::Channel> }}\n")
            lines.append(f"    impl {service.name}Client {{\n        pub fn new(channel: tonic::transport::Channel) -> Self {{ Self {{ inner: tonic::client::Grpc::new(channel).max_decoding_message_size(4 * 1024 * 1024).max_encoding_message_size(4 * 1024 * 1024) }} }}\n")
            lines.append("        pub fn with_max_message_bytes(mut self, limit: usize) -> Self { self.inner = self.inner.max_decoding_message_size(limit).max_encoding_message_size(limit); self }\n")
            for method in service.method:
                req, res = types[method.input_type], types[method.output_type]
                into = f"tonic::IntoStreamingRequest<Message = {req}>" if method.client_streaming else f"tonic::IntoRequest<{req}>"
                output = f"tonic::Streaming<{res}>" if method.server_streaming else res
                rpc = {(False, False): "unary", (False, True): "server_streaming", (True, False): "client_streaming", (True, True): "streaming"}[method.client_streaming, method.server_streaming]
                convert = "into_streaming_request" if method.client_streaming else "into_request"
                lines.append(f"        pub async fn {snake(method.name)}(&mut self, request: impl {into}) -> Result<tonic::Response<{output}>, tonic::Status> {{\n")
                lines.append('            self.inner.ready().await.map_err(|e| tonic::Status::unavailable(e.to_string()))?;\n')
                lines.append(f'            self.inner.{rpc}(request.{convert}(), tonic::codegen::http::uri::PathAndQuery::from_static("/{file.package}.{service.name}/{method.name}"), crate::codec::OfficialCodec::<{req}, {res}>::new()).await\n        }}\n')
            lines.append("    }\n}\n")
    return "".join(lines).encode()


def generate(protoc, plugin, include, output):
    version = subprocess.check_output([protoc, "--version"], text=True).strip()
    if version != "libprotoc 34.0":
        raise SystemExit(f"expected protoc 34.0, found {version}")
    inputs = sorted(path.relative_to(base).as_posix() for base in INCLUDES for path in base.rglob("*.proto"))
    services = [path for path in inputs if "/job_management/" in path or "/fn_execution/" in path]
    mapping = output / "crate_mapping.txt"
    wkts = sorted((include / "google/protobuf").glob("*.proto"))
    if not wkts:
        raise SystemExit("--include must contain google/protobuf/*.proto from protoc 34.0")
    mapping.write_text("protobuf_well_known_types\n" + str(len(wkts)) + "\n" +
                       "".join("google/protobuf/" + path.name + "\n" for path in wkts))
    common = [protoc] + [f"-I{path}" for path in [*INCLUDES, include]]
    run(common + [f"--rust_out={output}",
                  f"--rust_opt=experimental-codegen=enabled,kernel=upb,crate_mapping={mapping}",
                  f"--descriptor_set_out={output / 'model.pb'}", "--include_imports", *inputs])
    run(common + [f"--plugin=protoc-gen-rust-grpc={plugin}",
                  f"--rust-grpc_out={output}",
                  "--rust-grpc_opt=client_only=true,message_module_path=crate", *services])
    generated = {}
    modules = []
    official_modules = []
    replacements = 0
    for path in sorted(output.rglob("*.rs")):
        if path.name == "generated.rs":
            continue
        source = path.read_text()
        # protoc 34.0 emits TriggerView::default(), which resolves to Beam's
        # `default` field getter instead of the Default trait (E0061/E0308).
        # Qualify only these generated trait calls; do not change Beam's model.
        source, count = re.subn(
            r"((?:super::)+TriggerView)::default\(\)",
            r"<\1 as ::std::default::Default>::default()", source)
        replacements += count
        generated["generated/" + path.name] = (HEADER + "// @generated; see tools/generate.py.\n" + source).encode()
        name = path.name.replace(".u.pb.rs", "").replace(".pb.rs", "")
        target = official_modules if "_grpc.pb.rs" in path.name else modules
        target.append(f'    mod {name} {{ include!("generated/{path.name}"); }}\n    pub use {name}::*;\n')
    if replacements != 18:
        raise SystemExit(f"expected 18 TriggerView fixes, found {replacements}; review generator workaround")
    generated["generated.rs"] = (HEADER + "// @generated by tools/generate.py.\n" +
                                  "#[allow(warnings, clippy::all)]\nmod generated {\n" +
                                  "".join(modules) + "}\npub use generated::*;\n").encode()
    generated["official_clients.rs"] = (HEADER + "// @generated by tools/generate.py.\n" +
                                        "#[allow(warnings, clippy::all)]\nmod bindings {\n" +
                                        "".join(official_modules) + "}\npub use bindings::*;\n").encode()
    generated["tonic_clients.rs"] = tonic_clients((output / "model.pb").read_bytes())
    generated["urns.rs"] = constants((output / "model.pb").read_bytes())
    hashes = [f'{hashlib.sha256((base / path).read_bytes()).hexdigest()}  {path}\n'
              for path in inputs for base in INCLUDES if (base / path).exists()]
    generated["generated/model.sha256"] = "".join(hashes).encode()
    return generated


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--protoc", default=os.environ.get("PROTOC", "protoc"))
    parser.add_argument("--plugin", default=os.environ.get("PROTOC_GEN_RUST_GRPC", "protoc-gen-rust-grpc"))
    parser.add_argument("--include", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="beam-rust-generation-") as temporary:
        generated = generate(args.protoc, args.plugin, args.include, Path(temporary))
    stale = set(path.relative_to(MODEL).as_posix() for path in (MODEL / "generated").glob("*")) - generated.keys()
    changed = []
    for name, contents in generated.items():
        path = MODEL / name
        if not path.exists() or path.read_bytes() != contents:
            changed.append(name)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(contents)
    if args.check and (changed or stale):
        raise SystemExit("outdated generated sources: " + ", ".join(sorted(set(changed) | stale)))
    if not args.check:
        for name in stale:
            (MODEL / name).unlink()
    vectors = REPO / "model/fn-execution/src/main/resources/org/apache/beam/model/fnexecution/v1/standard_coders.yaml"
    packaged_vectors = SDK / "crates/beam-coders/tests/data/standard_coders.yaml"
    if args.check:
        if packaged_vectors.read_bytes() != vectors.read_bytes():
            raise SystemExit("packaged coder vectors differ from the authoritative model")
    else:
        packaged_vectors.write_bytes(vectors.read_bytes())
    print(f"{'Checked' if args.check else 'Generated'} {len(generated)} files (18 qualified Default calls)")


if __name__ == "__main__":
    main()
